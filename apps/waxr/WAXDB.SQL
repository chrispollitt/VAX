-- WAXDB.SQL -- WAX & TAPE schema for DEC Rdb (interactive SQL).
-- Run:  $ SQL
--       SQL> @WAXDB
-- The database file name comes from the logical WAXDB (see BUILD_WAXR.COM).
--
-- An ALBUM is the music; a HOLDING is a physical thing you own
-- (LP, cassette, 12in single...).  Own Rio twice?  Two holdings.

CREATE DATABASE FILENAME 'WAXDB'
    NUMBER OF USERS 10;

CREATE TABLE ARTIST (
    ARTIST_ID       INTEGER,
    ARTIST_NAME     CHAR(32),
    ORIGIN          CHAR(16),
    HAIR_SCORE      SMALLINT);

CREATE UNIQUE INDEX ARTIST_ID_NDX   ON ARTIST (ARTIST_ID);
CREATE UNIQUE INDEX ARTIST_NAME_NDX ON ARTIST (ARTIST_NAME);

CREATE TABLE ALBUM (
    ALBUM_ID        INTEGER,
    ARTIST_ID       INTEGER,
    ALBUM_TITLE     CHAR(40),
    RELEASE_YEAR    SMALLINT,
    RECORD_LABEL    CHAR(20),
    GENRE           CHAR(16));

CREATE UNIQUE INDEX ALBUM_ID_NDX     ON ALBUM (ALBUM_ID);
CREATE INDEX        ALBUM_ARTIST_NDX ON ALBUM (ARTIST_ID);

CREATE TABLE HOLDING (
    HOLDING_ID      INTEGER,
    ALBUM_ID        INTEGER,
    MEDIA_CODE      CHAR(1),
    GRADE           CHAR(3),
    PRICE_CENTS     INTEGER,
    BOUGHT_YEAR     SMALLINT,
    HOLDING_NOTES   CHAR(40));

CREATE UNIQUE INDEX HOLDING_ID_NDX    ON HOLDING (HOLDING_ID);
CREATE INDEX        HOLDING_ALBUM_NDX ON HOLDING (ALBUM_ID);

COMMIT;
